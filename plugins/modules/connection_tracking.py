from ansible.module_utils.basic import AnsibleModule
from ansible_collections.mikrotik.routeros_rest.plugins.module_utils.config_resource import run_config

DOCUMENTATION = r"""
---
module: connection_tracking
short_description: Manage RouterOS connection tracking settings through the REST API
description:
  - Reconciles the RouterOS global connection-tracking settings.
  - The settings dictionary contains RouterOS connection-tracking properties.
  - The singleton settings are reset to defaults when state is absent.
version_added: '1.0.0'
author:
  - Tony Reveal (https://github.com/tonyreveal)
options:
  host:
    description: RouterOS REST base URL.
    type: str
    required: true
  username:
    description: RouterOS REST username.
    type: str
    required: true
  password:
    description: RouterOS REST password.
    type: str
    required: true
    no_log: true
  settings:
    description: RouterOS connection-tracking properties.
    type: dict
    required: true
    suboptions:
      enabled:
        description: Whether connection tracking is enabled.
        type: bool
      tcp_established_timeout:
        description: TCP established connection timeout.
        type: str
      udp_timeout:
        description: UDP connection timeout.
        type: str
      icmp_timeout:
        description: ICMP connection timeout.
        type: str
  state:
    description: Desired settings state.
    type: str
    choices: [present, absent]
    default: present
  validate_certs:
    description: Validate the RouterOS TLS certificate.
    type: bool
    default: true
  timeout:
    description: HTTP timeout in seconds.
    type: int
    default: 30
requirements:
  - Python 3.
  - RouterOS 7.x with REST API enabled.
  - Ansible 2.16 or newer.
seealso:
  - name: RouterOS REST API documentation
    link: https://help.mikrotik.org/docs/display/ROS/REST+API
attributes:
  check_mode:
    description: Supports check mode without changing the device.
    support: full
"""


def main() -> None:
    module = AnsibleModule(
        argument_spec={
            "host": {"type": "str", "required": True},
            "username": {"type": "str", "required": True},
            "password": {"type": "str", "required": True, "no_log": True},
            "settings": {"type": "dict", "required": True},
            "state": {"type": "str", "choices": ["present", "absent"], "default": "present"},
            "validate_certs": {"type": "bool", "default": True},
            "timeout": {"type": "int", "default": 30},
        },
        supports_check_mode=True,
    )
    p = module.params
    settings = {key.replace("_", "-"): value for key, value in p["settings"].items()}
    run_config(module, "ip/firewall/connection-tracking", {}, settings)


if __name__ == "__main__":
    main()
