from ansible.module_utils.basic import AnsibleModule
from ansible_collections.mikrotik.routeros_rest.plugins.module_utils.config_resource import run_config

DOCUMENTATION = r"""
---
module: neighbor_discovery
short_description: Manage RouterOS neighbor discovery settings through the REST API
description:
  - Creates, updates, or removes a neighbor discovery interface setting.
  - The settings dictionary contains RouterOS neighbor discovery properties.
version_added: '1.0.0'
author:
  - Tony Reveal (https://github.com/tonyreveal)
options:
  host:
    description: RouterOS REST base URL.
    type: str
    required: true
  username:
    description: RouterOS REST username.
    type: str
    required: true
  password:
    description: RouterOS REST password.
    type: str
    required: true
    no_log: true
  interface:
    description: Interface identity.
    type: str
    required: true
  settings:
    description: RouterOS neighbor discovery properties.
    type: dict
    required: true
    suboptions:
      discover:
        description: Discovery protocols enabled on the interface.
        type: list
        elements: str
      discover_interface_list:
        description: Interface list eligible for discovery.
        type: str
      lldp_med_net_policy:
        description: LLDP-MED network policy.
        type: str
  state:
    description: Desired setting state.
    type: str
    choices: [present, absent]
    default: present
  validate_certs:
    description: Validate the RouterOS TLS certificate.
    type: bool
    default: true
  timeout:
    description: HTTP timeout in seconds.
    type: int
    default: 30
requirements:
  - Python 3.
  - RouterOS 7.x with REST API enabled.
  - Ansible 2.16 or newer.
attributes:
  check_mode:
    description: Supports check mode without changing the device.
    support: full
"""


def main() -> None:
    module = AnsibleModule(
        argument_spec={
            "host": {"type": "str", "required": True},
            "username": {"type": "str", "required": True},
            "password": {"type": "str", "required": True, "no_log": True},
            "interface": {"type": "str", "required": True},
            "settings": {"type": "dict", "required": True},
            "state": {"type": "str", "choices": ["present", "absent"], "default": "present"},
            "validate_certs": {"type": "bool", "default": True},
            "timeout": {"type": "int", "default": 30},
        },
        supports_check_mode=True,
    )
    p = module.params
    settings = {key.replace("_", "-"): value for key, value in p["settings"].items()}
    run_config(module, "ip/neighbor/discovery-settings", {"interface": p["interface"]}, {"interface": p["interface"], **settings})


if __name__ == "__main__":
    main()
